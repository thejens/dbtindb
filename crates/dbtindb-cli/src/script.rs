//! The SQL script that loads a project into a database's `dbtindb_files`.

use crate::project::File;

#[derive(Clone, Copy, Debug, PartialEq, Eq, clap::ValueEnum)]
pub enum Dialect {
    Postgres,
    Sqlite,
}

/// How the script treats rows already in the table.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mode {
    /// The table ends up holding exactly the project: files deleted on
    /// disk disappear from it.
    Replace,
    /// Files are inserted or updated; other rows stay.
    Merge,
}

/// A script that runs in one transaction, for `psql` or `sqlite3` (or any
/// client that runs several statements).
pub fn script(dialect: Dialect, table: &str, mode: Mode, origin: &str, files: &[File]) -> String {
    let mut out = format!(
        "-- Generated by `dbtindb load` from {origin}: {} files.\n",
        files.len()
    );
    out.push_str("BEGIN;\n");
    if dialect == Dialect::Sqlite {
        // The PostgreSQL extension creates its table; on SQLite it is ours.
        out.push_str(&format!(
            "CREATE TABLE IF NOT EXISTS {table} (path TEXT PRIMARY KEY, source TEXT NOT NULL);\n"
        ));
    }
    if mode == Mode::Replace {
        out.push_str(&format!("DELETE FROM {table};\n"));
    }
    for f in files {
        // One statement per file: no client or server limit on the size of
        // a VALUES list applies, and an error names a single file.
        out.push_str(&format!(
            "INSERT INTO {table} (path, source) VALUES ({}, {})\n  ON CONFLICT (path) DO UPDATE SET source = excluded.source;\n",
            quoted(Dialect::Sqlite, &f.path),
            quoted(dialect, &f.source),
        ));
    }
    out.push_str("COMMIT;\n");
    out
}

/// A string literal that survives the client as well as the server.
fn quoted(dialect: Dialect, text: &str) -> String {
    match dialect {
        // Standard SQL quoting; SQLite has no escapes besides ''.
        Dialect::Sqlite => format!("'{}'", text.replace('\'', "''")),
        // Dollar quoting: the text goes through verbatim, whatever
        // standard_conforming_strings says about backslashes, and psql
        // neither interpolates :variables nor reads backslash commands in it.
        Dialect::Postgres => {
            let tag = (0..)
                .map(|n| {
                    if n == 0 {
                        "$dbt$".to_owned()
                    } else {
                        format!("$dbt{n}$")
                    }
                })
                .find(|tag| !text.contains(tag.as_str()))
                .expect("some tag does not occur in the text");
            format!("{tag}{text}{tag}")
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn file(path: &str, source: &str) -> File {
        File {
            path: path.into(),
            source: source.into(),
        }
    }

    #[test]
    fn quotes_for_each_client() {
        assert_eq!(quoted(Dialect::Sqlite, "it's"), "'it''s'");
        assert_eq!(
            quoted(Dialect::Postgres, r"a\n 'b' :c"),
            r"$dbt$a\n 'b' :c$dbt$"
        );
        assert_eq!(
            quoted(Dialect::Postgres, "x $dbt$ $dbt1$"),
            "$dbt2$x $dbt$ $dbt1$$dbt2$"
        );
    }

    #[test]
    fn replaces_or_merges() {
        let files = [file("models/a.sql", "select 'a'")];
        assert_eq!(
            script(
                Dialect::Sqlite,
                "dbtindb_files",
                Mode::Replace,
                "shop",
                &files
            ),
            "-- Generated by `dbtindb load` from shop: 1 files.\n\
             BEGIN;\n\
             CREATE TABLE IF NOT EXISTS dbtindb_files (path TEXT PRIMARY KEY, source TEXT NOT NULL);\n\
             DELETE FROM dbtindb_files;\n\
             INSERT INTO dbtindb_files (path, source) VALUES ('models/a.sql', 'select ''a''')\n  \
             ON CONFLICT (path) DO UPDATE SET source = excluded.source;\n\
             COMMIT;\n"
        );
        let pg = script(
            Dialect::Postgres,
            "dbt.dbtindb_files",
            Mode::Merge,
            "shop",
            &files,
        );
        assert!(
            !pg.contains("DELETE") && !pg.contains("CREATE TABLE"),
            "{pg}"
        );
        assert!(
            pg.contains("VALUES ('models/a.sql', $dbt$select 'a'$dbt$)"),
            "{pg}"
        );
    }
}
